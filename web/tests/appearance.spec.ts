import { test, expect, origin } from './fixtures'

test('light and dark themes follow the device, switch from the top bar and persist per account', async ({ page, harness }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto(origin)
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'Switch to light mode' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect.poll(() => harness.prefs.theme).toBe('light')
  const bg = await page.evaluate(() => getComputedStyle(document.body).backgroundColor)
  expect(bg).toBe('rgb(244, 245, 247)')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.goto(origin + '/settings')
  await page.getByRole('radio', { name: /Automatic/ }).click()
  await expect.poll(() => harness.prefs.theme).toBe('system')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
})

test('accent colour and larger text apply everywhere, including before sign-in', async ({ page, context, harness }) => {
  await page.goto(origin + '/settings')
  await page.getByRole('radio', { name: 'Violet' }).click()
  await page.getByRole('radio', { name: 'Large' }).click()
  await expect.poll(() => harness.prefs).toMatchObject({ accent: 'violet', text_size: 'large' })
  await expect(page.locator('html')).toHaveAttribute('data-accent', 'violet')
  expect(await page.evaluate(() => getComputedStyle(document.documentElement).fontSize)).toBe('18px')
  await context.route('**/api/v1/auth/status', route => route.fulfill({ json: { authenticated: false, user: null, needs_setup: false, oidc: true, password_login: false } }))
  await page.goto(origin + '/login')
  await expect(page.locator('html')).toHaveAttribute('data-accent', 'violet')
  await expect(page.locator('html')).toHaveAttribute('data-text', 'large')
})

test('home speaks plainly about a broken app and help is one click away', async ({ page, harness }) => {
  harness.apps[3] = { ...harness.apps[3], status: 'down' }
  await page.goto(origin)
  await page.getByRole('button', { name: 'Habits isn’t responding' }).click()
  await expect(page.getByRole('dialog')).toContainText('This app isn’t responding right now.')
  await page.keyboard.press('Escape')
  await page.getByRole('link', { name: 'Help', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Help', exact: true })).toBeVisible()
  await page.getByText('Who can see my things?').click()
  await expect(page.getByText(/own account/)).toBeVisible()
  await page.goto(origin + '/apps')
  await expect(page.locator('.app-card').filter({ hasText: 'Habits' })).toContainText('Not responding right now')
  await expect(page.locator('.app-card').filter({ hasText: 'Kitchen' })).toContainText('Recipes, meal plans')
})

test('the getting started guide tracks progress and can be dismissed', async ({ page, harness }) => {
  await page.goto(origin)
  const guide = page.getByRole('region', { name: 'Getting started' })
  await expect(guide).toBeVisible()
  await page.getByRole('button', { name: 'Open Pocket Notes', exact: true }).click()
  await page.getByRole('link', { name: 'Home', exact: true }).first().click()
  await expect(guide.locator('.done')).toContainText('Open your first app')
  await guide.getByRole('button', { name: 'Hide the getting started guide' }).click()
  await expect.poll(() => harness.prefs.welcome_done).toBe(true)
  await expect(guide).toHaveCount(0)
})
