  await moveClock.focus()
  await page.keyboard.press('End')
  await expect(page.locator('.widget-slot').last()).toHaveAttribute('data-widget-id', 'home-clock')
  await page.keyboard.press('Home')
  await expect(page.locator('.widget-slot').first()).toHaveAttribute('data-widget-id', 'home-clock')
