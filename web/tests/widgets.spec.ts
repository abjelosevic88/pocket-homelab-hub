test('notes survive a failed save and edits made while an earlier save is in flight', async ({ page, context, harness }) => {
  harness.prefs = { home_widgets: [widget('note', { note: 'Original' })] }
  harness.saveFails = true
  await page.goto(origin)
  await page.getByRole('button', { name: 'Edit Quick note', exact: true }).click()
  await page.getByLabel('Your note').fill('Keep this thought')
  await page.getByRole('button', { name: 'Save widget' }).click()
  await expect(page.getByRole('alert')).toContainText('haven’t saved')
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Quick note widget' })).toContainText('Keep this thought')
  let release: () => void = () => {}, requested: () => void = () => {}
  const gate = new Promise<void>(resolve => { release = resolve })
  const started = new Promise<void>(resolve => { requested = resolve })
  let held = false
  await context.route('**/api/v1/prefs', async route => {
    if (route.request().method() === 'PUT' && !held) {
      held = true; requested(); await gate
    }
    await route.fallback()
  })
  harness.saveFails = false
  await page.getByRole('button', { name: 'Try again', exact: true }).click()
  await started
  await page.getByRole('button', { name: 'Edit Quick note', exact: true }).click()
  await page.getByLabel('Your note').fill('The latest thought wins')
  await page.getByRole('button', { name: 'Save widget' }).click()
  release()
  await expect.poll(() => harness.prefs.home_widgets?.[0]?.config.note).toBe('The latest thought wins')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.locator('.widget-save-status')).toHaveText('Personal to your account')
  await page.reload()
  await expect(page.getByRole('article', { name: 'Quick note widget' })).toContainText('The latest thought wins')
})

